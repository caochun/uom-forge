- 描述某个对象的信息可保留为属性或从属结构；需要独立识别、引用或承载业务状态与联系的概念才考虑成为对象。不要从名词清单直接决定对象，也不要把所有事实强行套成同一种句式。
- 联系自身带有时间、角色或状态，同一批参与者存在需要区分的不同安排，或其他业务事实需要引用这次联系时，明确关系上下文；已有表达无法唯一绑定这些事实时，再考虑将联系建成业务事项对象。关系实体化不额外要求持久保存或历史追踪。
- 分开表达关系的数量与可选性、跨实例或记录的约束，以及操作执行时的前提。写清每项限制适用的时间和上下文；多值关系不能代替限定上下文中的唯一性，状态属性不能代替操作前提。
