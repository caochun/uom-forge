import type { UnderstandingSources } from '../../shared/analysis.ts'
import { businessContextPrompt } from '../stages/business-context.ts'
import { ANALYST_INSTRUCTIONS } from './common.ts'

export interface BasisCorrection { previous: string; feedback: string }

export function businessBasisPrompt(narrative: string, sources?: UnderstandingSources, correction?: BasisCorrection): string {
  return `${ANALYST_INSTRUCTIONS}
你现在处于“建模依据”阶段。建模依据是一份领域语义需求说明，供模型设计和表达检查共同使用。

它必须回答两个问题：
1. 领域模型必须直接表达哪些业务事实和约束？
2. 智能体在给定目标、当前状态和业务上下文时，必须能够根据这些语义推理出哪些已知业务计划、分支和结果？

阶段边界：
- 使用下方业务来源及其优先关系提炼语义；对照已提供原文，校核整理稿是否遗漏、误读或把推断改强。用户保存的整理稿保持原样，校正说明写入本次依据。
- 只提炼业务来源能够支持的语义，不猜测未提供的原文，不补造业务；原文已明确而整理稿遗漏的要求应补回，并注明原文位置。
- 建模依据描述“需要表达什么、需要推理什么”，不决定对象如何拆分、关系如何连接、操作归谁，也不把流程设计成模型元素。
- 已知业务计划或流程要保留为模型表达和推理的目标；它们不是领域模型中的流程定义。

输出形式：
- 输出简洁、可审阅的自然语言 Markdown，不要求 JSON，也不要求固定的机器协议。
- 建议按“业务范围与目标”“必须表达的事实”“必须保留的约束”“已知业务计划或流程（表达与推理目标）”“业务案例”“未决边界”组织。
- 每项内容写出完整语义。可以编号以便回看，但不要为了凑编号或章节编造内容。
- 每项内容保留支持它的整理稿语句或段落名称；不编造原文引文或编号。
- 区分原文明示、明确条件必然推出的结论、候选解释和真正的业务未知；推导写明条件与适用范围，候选解释不能进入确定规则。来源未要求如何建模，不构成业务未知。

必须表达的事实：
- 每项事实表示一条模型需要直接表达的业务判断，可以是静态状态、业务联系、一次变化及其结果，或结果与其归属。
- 按事实需要写清主体、业务事项、时间与共同上下文、参与角色、条件、动作或变化、结果、归属和适用范围；整理稿不支持的部分保持未知。
- 区分实际发生的事实、拟议安排和仅用于当次计算的临时结果。临时结果不自动变成需要保存或追踪的业务对象。
- 保留业务含义要求的实例区分、对应关系、状态变化和结果归属，不要求整理稿使用“独立身份”等建模术语。整理稿区分模板与实例、记录或结果时保留区别；不额外假定次数、历史追踪、保存期限或排他限制。

必须保留的约束：
- 把整理稿明确的业务规则写成模型需要保留的语义约束，说明它限制哪些事实、变化、操作或推理结果。
- 同时保留限制与明确允许的情况，不用常见业务惯例覆盖整理稿中的许可。数量、可选性、跨实例或记录的唯一性和操作前提分别说明，并保留各自适用的时间与上下文。
- 保留适用范围、前提、例外、阈值、单位、逻辑组合、优先级、公式、否决条件和结果归属；时间限制要说明从什么事件开始、限制哪个事项、到期产生什么后果。相同的时长不代表同一个期限；必要条件未给出时保持未决，不能用“按规定”“满足条件”或“见整理稿”代替具体内容。

已知业务计划或流程：
- 已知业务计划或流程是模型设计需要支持的已知业务内容，不是最终领域模型中的流程元素。
- 对每个重要计划或流程，按整理稿实际提供的程度说明目标、参与者、业务事项、触发前提和上下文、已知步骤及其顺序或因果、分支、状态变化、结果和结果归属。
- 区分业务强制的先后依赖与叙述顺序、某次安排。前者是必须保留的业务约束，后者作为已知路径保留，不自动要求模型只允许这一条路径。
- 说明需要由智能体推理的动作、分支和结果；可以从已明确的条件和规则推导，但须写明依据，不增加业务活动、规则或未说明的前提。

业务案例：
- 业务案例是从已列出的事实、规则或已知业务计划中抽出的具体业务实例，用来说明领域模型需要表达什么，或智能体需要根据模型推理出什么；它不是领域模型中的流程定义。
- 表达案例用于说明模型需要直接表达的事实、关系、状态或结果归属。按需要写清业务上下文、涉及的主体和事项、已有状态或关系，以及预期表达。
- 推理案例按需要写清初始上下文、目标或触发条件、适用规则，以及预期的动作、分支、状态变化或结果归属。把案例给定的事实与需要模型支持的推理分开写，预期结果不能当作已知前提。
- 业务含义要求区分不同实例、安排、状态或结果时，优先用只改变一个关键条件的对照案例说明区别；分别保留两侧有依据的预期，包括明确允许的情况。边界结论尚未确定时标明未决，不为凑案例补出规则，也不强求每种案例类型都出现。
- 每个案例标明对应的事实、规则或计划。为说明语义而设定的示例实例须注明假设，不升级为实际业务事实，也不要求模型存储这些示例。
- 整理稿不足以支持具体案例时说明缺少什么；后续设计和检查可以从已有事实、规则或计划中补充少量案例，但不能引入新的业务要求。
- 对核心业务过程保留贯穿输入、选择或变化、结果的完整场景；指出每步需要什么业务信息、来自哪里、后续用于什么。不要只列规则分支而漏掉结果本身的业务含义，也不在依据阶段决定属性或关系的实现方式。

不确定性与边界：
- 区分整理稿明确的内容、有依据的推导和未决内容。上下文唯一确定的含义，以及不增加前提、从明确规则必然推出的结果，可以作为要求并注明依据；多种可能解释或依赖额外假设的内容保留未决。
- 用户已保存的确认更新对应的旧解释；问题选项、待确认解释和示例假设不是确认结果。
- 保留歧义、矛盾、术语不一致、数字或公式问题，以及影响明确业务要求的必要信息缺失，并说明业务影响；未涉及的业务或实现细节不自动变成待补需求。
- 未决或冲突内容可以作为待确认边界；依赖某一种未决解释的业务案例要标明受业务澄清影响，不能用它宣称模型已经通过。

输出前核对：
- 回看整理稿中会影响业务判断的限制、明确许可、例外、对应关系和时间起点，确认它们已进入依据且含义一致；再核对依据中的确定结论能否由整理稿支持，有推导时写明所用条件。发现遗漏或无依据限制时修正对应正文。
- 核对案例是否保留这些关键区别，不能只留下顺利完成的路径。核对属于本次提炼工作，不额外输出自评通过声明，不要求逐句映射或固定机器协议。

${businessContextPrompt({ narrative, sources })}
${correction ? `本次任务为依据校正：输出完整的新依据，保留未受影响的要求和案例标识。逐项核对审阅指出的问题，只修正业务来源能直接支持的提炼错误；需要选择业务解释的内容保留未决。简要记录修正了什么、所据来源及受影响案例；案例预期只有来源支持时才可改变，不能为通过检查删除失败案例。不得修改用户确认或借机增加业务规则。
上版依据（待校正内容，不是新增事实）：\n${JSON.stringify(correction.previous)}
审阅意见（定位问题，不是业务来源）：\n${JSON.stringify(correction.feedback)}` : ''}`
}

