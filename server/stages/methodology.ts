export const MODELING_METHOD = `建模方法：
- 核心问题是：${CORE_QUESTION}
- 业务案例是建模依据中语义的具体化，不是模型元素。逐项保留已有案例；只有案例不足以暴露明确边界时，才从明确的事实、规则或计划补充少量案例，且不得新增业务要求。
- 对每个案例先确定必须保留的实例或事项、参与者、共同上下文、前提、联系、状态变化、结果及归属，再选择能直接表达或支持推理的最小元素集合。
- 建模顺序通常是：确定对象边界；用关系绑定参与者、事项和上下文；用业务操作表达副作用；用只读能力表达查询、计算、模拟和校核；用规则表达条件、阈值、公式、例外、优先级和否决。
- 回放已知计划或过程：让智能体从目标、当前上下文和规则推理必要操作、分支、状态变化和结果。计划的顺序本身不成为流程、任务或编排元素。
- 清晰描述、从属结构和可唯一确定的关系路径都可以表达事实；同名元素或“支持追踪”不能作为证据。不要为了凑类型把每个名词、角色、步骤或结果都建成对象。
- 同一对象之间存在多次事项、多个实例、不同安排或多种角色且业务要求区分时，模型必须保留足够的上下文或关系来区分；没有这类要求时不要增加配对、历史或独立记录。
- 已有表达足够清楚时保留；只有明确事实无法表达、业务上不同的案例无法区分，或定义互相矛盾时才调整。业务没有答案时保留边界，不把设计偏好写成业务约束。
- 业务案例中的示例实例只用于检查，不能升级为新的事实；业务依据没有说明的身份、次数、历史、保存或排他限制，不能凭常识补入。

对照案例只用于说明检查方法：若业务要求区分“参与者 A 使用资源 X、参与者 B 使用资源 Y”和交换资源后的安排，模型必须表达对应绑定；若业务只要求知道参与者和资源清单，则不需要新增配对；若业务要求追踪每次结果，模型必须能区分不同事件的结果，否则只保留当前值。`

