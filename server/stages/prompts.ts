检查影响理解的明显问题：术语不一致、指代不明、语句歧义、条件或结论缺失、前后矛盾，以及文字、列表、数字和公式之间的不一致。能够由上下文明确解决的可直接整理；不能确定的保留相关说法，说明问题及影响，不擅自选取解释或纠正数值。
