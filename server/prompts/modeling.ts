import type { ModelingInput } from '../../shared/analysis.ts'
import type { DesignAcceptance } from '../../shared/design-acceptance.ts'
import { businessContextPrompt } from '../stages/business-context.ts'
import { modelContext } from '../stages/model-context.ts'
import { MODELING_METHOD } from '../stages/methodology.ts'
import { CARGO_MODELING_EXAMPLE } from '../stages/modeling-example.ts'
import { ANALYST_INSTRUCTIONS } from './common.ts'

export function modelDesignPrompt(
  input: Pick<ModelingInput, 'currentModel' | 'feedback'> & Partial<Pick<ModelingInput, 'narrative' | 'sources'>>,
  businessBasis: string,
  acceptance?: DesignAcceptance,
): string {
  const current = modelContext(input.currentModel)
  return `${ANALYST_INSTRUCTIONS}
你是领域语义建模者。模型设计阶段请从给定的建模依据形成一份候选领域模型设计，作为供智能体理解业务的语义底座。

输入边界：
- 实际任务的建模依据组织本次设计的事实、规则、已知计划、业务案例和未决边界；同时使用提供的业务来源核对，不能因某项推断已进入依据就视为确定事实。依据有误应明确指出并交由检查工具触发依据校正，不在设计中暗自另立一套业务要求。教学示例仅说明方法。
- 业务案例约束设计充分性：模型应能表达案例中的实例及其联系，不需要把每个具体实例建成一个对象类型或保存示例数据。
- 用户反馈只在建模依据内指导表达调整，当前候选模型用于比较与修订，不能反过来证明业务要求。反馈提出新增或修改业务事实、规则时，注明应先更新业务理解和建模依据，本次设计不据此改变业务要求。

输出要求：
- 输出一份可独立阅读的 Markdown 设计，按需要使用“模型概述”“对象”“关系”“业务操作”“只读能力”“业务规则”“建模判断与未决边界”等标题；没有内容的类型可省略。
- 每个定义写清业务语义、适用条件、作用对象或关系端点、必要的实例/事项归属和对推理的作用。业务判断依赖的属性、输入、状态与时间含义要落在对应定义中，不能只写能力名称或放在模型概述里；不要重复抄写建模依据、计划或案例全文。
- 业务案例、已知计划和检查报告不成为模型元素；用自然语言定义必要的业务属性、状态和输入，本阶段不设计数据库字段、接口或算法实现。

元素定义：
- 对象：需要独立识别、持续引用、承载状态或关系，或作为业务事项、记录、产出被管理的概念；按业务含义确定必要的实例区分，不要求建模依据使用“独立身份”等建模术语。属性、状态、指标和临时计算结果不自动成为对象。
- 关系：表达真实业务联系；写清两端对象、方向、共同上下文、参与绑定或结果归属，以及依据支持的数量与可选性。未明确的上下限不擅自补定；仅共同出现在同一事项中的概念不自动形成关系。
- 业务操作：会创建或改变对象、关系或业务状态的行为；写清作用对象、输入语义、前提、状态变化、效果及结果归属。流程步骤只有包含这类变化时才提炼为操作。
- 只读能力：不改变业务状态的查询、计算、模拟、校核或评估；写清输入语义、适用条件和输出。只有明确产生持久业务记录或状态变化时才用业务操作。
- 业务规则：绑定到对象、关系、操作或能力，写清条件、结果、例外、阈值、单位、公式、优先级和否决条件。
- 建模判断与未决边界：说明重要的合并/拆分或关系上下文如何保留必要区别，区分表示方式的选择与业务事实未决。记录未细化内容和仍未确定的业务事实；限制必须同时写入受影响定义，不能靠末尾免责声明覆盖设计中的假设。
- 原文事实、必然推导、建模表达选择和确需业务确认的未知分别处理。表达已知业务所需的属性、从属结构、关联和信息承接由建模者选择；给出语义依据即可，不要求原文逐字指定这些模型元素。不能把缺少建模术语当作缺少业务事实。
- “未要求保存”不等于“禁止保存”，也不自动要求持久保存；按业务需要给出清楚的信息承载或可推导路径。“未说明关系如何建模”不能豁免已有业务所必需的归属与联系。选择不得额外引入数量、生命周期、排他性或时序限制。
${MODELING_METHOD}
业务澄清：
- 只有新发现的歧义、冲突或必要信息缺失会影响明确业务要求的表达时，才增加“## 需要补充的业务信息”；已有未决不重复提问，设计偏好和未提出的场景不构成问题。
- 每个问题用“1. 问题”的编号列表，随后分行写“依据：建模依据原句”“歧义：不同解释、冲突或缺失的必要信息”“影响：对模型表达或推理的影响”。有合理选项时再写“选项：答案一；答案二”或“多选：答案一；答案二”；否则省略选项行。
- 设计继续保留未决边界，不假设用户答案；未决影响同时写入相关定义。

${CARGO_MODELING_EXAMPLE}

${input.narrative !== undefined ? businessContextPrompt({ narrative: input.narrative, sources: input.sources }) : '本次只提供建模依据，无法回看整理稿或原文。'}
实际任务的当前建模依据（组织业务要求；若工具返回已校正依据，以最新版本修订并复查）：
${JSON.stringify(businessBasis)}
${acceptance ? `本次固定业务验收清单（逐项落实到定义，问题及预期仍须有业务来源支持；不可作为新增业务事实）：\n${JSON.stringify(acceptance)}` : ''}
${current ? `当前候选模型（用于比较与修订，不是业务依据）：\n${JSON.stringify(current)}` : ''}
用户反馈（建模依据范围内的表达调整建议）：
${JSON.stringify(input.feedback || '')}`
}

