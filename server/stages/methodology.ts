export const MODELING_METHOD = `建模方法：
- 建模始终围绕这个问题：${CORE_QUESTION}
- 先使用建模依据已有的检验情形，再用同一份建模依据补充确实会暴露模型边界的情形。
- 对每个情形说明：哪些元素确定参与者和所属事项，哪些元素表示业务变化，哪些元素提供只读结果，哪些规则约束前提、变化和结果；判断智能体能否据此推理出必要步骤和结果。只使用该情形需要的元素类型。
- 建模依据来自文档整理稿，表示当前建模输入；它不表示原文已经被证实，也不表示业务已经穷尽。
- 已有表达足够清楚时保留；只有具体事实无法表达、业务上不同的情形无法区分，或定义之间互相矛盾时才调整。
- 需要调整时，再分析对象身份、参与角色、共同上下文、操作与只读能力、规则绑定等原因。这些是排查方向，不是必须逐项建立的清单。
- 优先保持语义完整并消除重复。普通属性可以暂不展开，但必要的身份、参与关系和结果归属必须明确。
- 稳定的关系推导、清晰的文字、规则组合和从属结构都可以表达事实；“支持追踪”或元素同名本身不能作为表达证据。不要为了凑类型把每个角色、步骤或结果都建成对象。
- 已知业务计划或流程是检验材料，不是待编译的模型元素；每项调整都要解决一个有依据的表达缺口，并重新检查受影响的情形和原来已经表达的事实。
- 业务本身没有答案时保留边界；另一种可选设计本身不是模型缺陷。把边界写在受影响的定义中，不靠末尾免责声明掩盖设计中的假设。
- 业务没有说明的前提、次数、身份、历史或排他限制，不得凭常识写成确定约束；同一事项不能一边声明未知，一边按某个假设限制操作或关系。

对照例子（只说明检查方法，不引入业务概念）：
- 如果业务要求记录“哪个参与者使用哪个资源”，模型必须能区分两种安排：参与者 A 使用资源 X、参与者 B 使用资源 Y；参与者 A 使用资源 Y、参与者 B 使用资源 X。只有“参与者清单”和“资源清单”时，这两种安排完全相同，因此不能表达对应关系。
- 如果业务只要求知道有哪些参与者和资源，没有要求记录参与者与资源的对应关系，就不需要增加“使用配对”或新的关联对象。
- 如果业务要求追踪每次发生的结果，模型必须能区分事件 E1 的结果和事件 E2 的结果。如果业务只要求当前值，没有历史追踪要求，就不自动增加历史对象。`

