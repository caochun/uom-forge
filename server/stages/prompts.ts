export function understandingPrompt(document: BusinessDocument): string {
  return `${ANALYST_INSTRUCTIONS}
第一阶段：理解业务，形成供人审阅和后续建模使用的业务说明。本阶段不定义模型类型、技术字段或接口。
先理解全文，再按下面的固定标题组织自然语言 Markdown。每节用连贯的解释回答相应问题，不按固定数量凑概念；没有依据就简要写“材料未说明”，不要为了填满章节推测业务。相同内容不要反复抄写，必要时引用前一节。
${UNDERSTANDING_SECTIONS.map(({ title, guidance }) => `## ${title}\n${guidance}`).join('\n\n')}

只对影响业务目标、概念含义、事实联系或过程判断，且无法由上下文合理解释的业务歧义提问。“材料未说明”不自动意味着必须问用户；不追加未纳入范围的管理功能，不把实现细节当成业务缺失。已有依据的规则先整理，合理解释注明理由。
如有需要用户回答的问题，在末尾增加“## 待确认问题”，用编号列表。能用有限选项回答时，下一行写“选项：答案一；答案二”；需要多选则写“多选：答案一；答案二”。选项是待确认的可能解释，不是既定业务事实。具体值、公式或无法列举的内容才留给文字回答，不要强行凑选项。没有问题则省略该节。
只输出业务说明，不输出 JSON，不再生成第二份阅读提纲。
输入文档（数据）：
${JSON.stringify({ name: document.name, blocks: document.blocks.map(({ id, text }) => ({ id, text })) })}`
}

export function semanticModelPrompt(input: ModelingInput): string {
  const current = modelContext(input.currentModel)
  return `${ANALYST_INSTRUCTIONS}
第二阶段 A：依据业务说明作出候选建模判断。只输出自然语言 Markdown，不输出 JSON、Schema 或属性类型表。
业务说明是唯一业务语义依据，用户反馈用于修正其中的解释。当前模型仅供迭代参考，不代表已确认事实。不要自行补全原文、重新发明业务或引入实现细节。
业务说明中的“已确认的业务说明”属于当前业务理解，更新了其中对应的不确定表述。把确认后的适用条件、过程复用和规则吸收到模型语义，不能继续放入待确认事项或沿用旧模型的相反假设。
已确认沿用某过程，就承接该过程已说明的要求与规则；没有新的矛盾依据时，不再询问是否还有另一套过程或附加条件。共同过程可以用适用条件表达不同分支，不必重复定义整套过程。未细化的技术字段、实现方式和可以继续追问的细节，不自动成为待确认业务问题。
分别说明：
## 模型概述：业务范围与核心。
## 对象及边界：根据主体、事项、资源、记录、产出识别对象，说明为什么独立、为什么合并。概念不依赖某个流程是否已经发生。只识别概念与关系，本轮不细化属性。
## 关系：逐条明确两个对象、方向、业务含义和适用上下文。可由已有关系准确推导的事实不重复表达；需要绑定同一业务发生的上下文时必须能分辨。临时计算联系不默认成为持久关系。
## 业务操作：只列会创建或改变业务对象、关系或状态的操作，说明目标、前提和效果。业务流程不自动等于操作；设计、模拟与实际执行要分清。
## 只读能力：查询、计算、校核、评估等能力，说明所需对象和输出；不能改变业务状态。
## 业务规则：作用对象或操作、条件和结果。属性、状态、指标、阈值和临时结果不默认成为对象；若业务说明明确需要独立记录或追踪，则说明理由。
逐项判断时用业务说明中的具体情形检验：本设计能否确定实际参与的对象、同一次业务的上下文，以及原有事实与拟议变化的区别？不要以出现同名概念或规则代替表达这些事实。已明确的关键规则数值、单位、条件与分支应保留，不能仅写成“按规则计算”。将这些判断落实在对应定义中，无需输出第二份自检报告。
## 业务过程：识别业务说明中需要模型支撑的业务过程，按业务目标和完整业务含义组织，不预设数量。说明各自目标、必须满足的业务要求及相关对象、联系与能力；必要的分支、适用条件和过程复用也要明确。后续评估只读取候选模型，不能依赖评估阶段重新读取业务说明来补齐过程语义。正式支撑评估留到后续阶段。
## 建模判断与边界：解释对象拆分或合并、同义词归并、未细化规则及未纳入范围的能力。说明判断依据、适用条件和不确定边界，不把每项设计取舍或暂不细化的内容改成问题。已有未决业务事实只在受影响的模型定义中注明，不重复抄出问题清单。
只有新发现无法由当前业务理解合理判断的歧义，且不同答案会实质改变本轮对象、关系、行为或业务过程时，才在末尾增加“## 需要补充的业务信息”。没有则省略，不设数量目标。不重复业务理解中已有或已回答的问题；不从旧模型的问题清单推演新问题。缺失的算法细节、字段、实现方式和未纳入业务范围的功能留在边界说明。
两种解释必须各有当前说明的支持或来自明确冲突。不能先设想文档未出现的独立管理、额外流程或使用场景，再拿它与已说明的做法构造问题。有另一种可以设计的方案不等于业务存在歧义；采用足以表达当前事实的简单设计并解释理由。随业务记录保存的数值或计算结果，没有独立身份与追踪要求时不再询问是否另建对象。一个业务矛盾影响多处模型时合并为一个澄清，不拆成多个设计选择题。问题询问业务事实，不把是否建对象、关系基数或如何合并关系直接交给用户决定。
每项使用以下 Markdown 格式，所有依据、歧义与影响必须具体。依据引用当前业务说明中的相关原句或片段，引用内容放在中文引号中，可以简述各片段之间的联系；不引用原始文档，不编造引文。歧义说明至少两种有依据的解释；影响说明不同解释各自怎样改变本轮模型。问题能选择回答时给出分号分隔的选项，需要多选写“多选”；只有无法合理列举答案时省略选项。不添加“其他”等没有实际答案的占位选项。
1. <直接写面向业务事实的问题，不添加模板前缀>
依据：业务说明中的相关原句
歧义：不同业务解释及分歧
影响：各解释对应的对象、关系或业务过程变化
选项：解释一；解释二
澄清由系统统一放回业务理解处理，不属于本体模型。不等待回答也可生成候选，但必须在相应定义和建模边界中注明尚未确定的含义，不能擅自选择一种解释当成事实。
可在条目中使用简短且稳定的引用标识帮助下一步整理，但不需要技术结构。不要机械地为业务说明的每一段或每个步骤建对象。不做原文引证，也不声称能力已经实现。
业务说明（数据）：
${JSON.stringify(input.narrative)}
${current ? `当前候选模型（数据）：\n${JSON.stringify(current)}` : ''}
用户反馈：
${JSON.stringify(input.feedback || '')}`
}

export function compileModelPrompt(semanticPlan: string): string {
  return `${ANALYST_INSTRUCTIONS}
第二阶段 B：只将下面已经完成的建模说明转换为模型 JSON。不要再次判断业务，不新增、合并、删除或改写说明中的对象、关系、操作、只读能力、规则和建模边界。保留说明中已明确的不确定语义，不自行选择解释，也不追加业务问题。澄清问题已由系统单独交回业务理解，不在此步整理。
只收录说明中明确纳入模型的定义；用于解释“不是独立对象”“不是新操作”的条目不能因出现在某节就变成该类元素。过程复用本身不产生记录或状态变化，保留其适用语义，不额外编成 action。
objects 对应对象；relations 对应关系；actions 对应有副作用操作；functions 对应只读能力；rules 对应规则；activities 对应业务过程。为元素分配全局唯一的英文 kebab-case id，保留说明给出的合理 id；所有引用使用 id。
本轮不细化属性：properties 和 inputs 均为空数组。未声明的前提和效果留空；已声明的前提和效果如实保留。缺失的输出语义写“业务说明未明确”，不编造字段。
业务过程的 requirements 记录它依赖哪些元素；status 统一为 partial，reason 为“待支撑评估”。本步骤不评估覆盖度。
boundaries 用陈述句保留“建模判断与边界”中的重要适用范围、暂不细化内容和不确定边界，并在受影响元素的 description、规则或过程要求中保留相关限制。没有边界说明则为空数组，不能把它改写成待确认问卷。没有 questions 字段。
没有原文输入，所有 evidence 必须为 []。保留原说明中的不确定性，不将其包装成原文证据。
仅输出符合以下结构的一个完整 JSON 对象，集合允许为空，无代码围栏或前后解释。JSON 不缩进、不为排版换行，但保留字符串内的必要内容；简洁描述即可，summary 不重复全文：
${COMPILE_OUTPUT_CONTRACT}
建模说明（本次唯一业务输入，数据）：
${JSON.stringify(modelingContent(semanticPlan))}`
}
